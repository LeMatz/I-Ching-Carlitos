/**
 * Fast lookup map from binary string (lines 1 to 6, bottom to top) to HexagramData
 */
export const HEXAGRAMS_BY_BINARY: Record<string, HexagramData> = Object.values(HEXAGRAMS).reduce(
  (acc, hex) => {
    acc[hex.binaryKey] = hex;
    return acc;
  },
  {} as Record<string, HexagramData>
);

export function getHexagramByNumber(num: number): HexagramData {
  return HEXAGRAMS[num] || HEXAGRAMS[1];
}

export function getHexagramByLines(lines: (0 | 1)[]): HexagramData {
  const key = lines.slice(0, 6).join('');
  return HEXAGRAMS_BY_BINARY[key] || HEXAGRAMS[1];
}
