export function getRecommendedAttitude(hexagramNumber: number, fallbackImage?: string): AttitudeAdvice {
  if (RECOMMENDED_ATTITUDES[hexagramNumber]) {
    return RECOMMENDED_ATTITUDES[hexagramNumber];
  }

  // Fallback extracting noble counsel from image text if ever needed
  if (fallbackImage) {
    const parts = fallbackImage.split(/(?:Así el noble|El noble|Así los antiguos reyes|Los reyes de antaño)/i);
    if (parts.length > 1) {
      const counsel = parts[1].trim();
      return {
        short: 'Templanza y rectitud',
        advice: `El noble ${counsel}`,
      };
    }
  }

  return {
    short: 'Templanza y rectitud',
    advice: 'Mantener la serenidad interior, no precipitarse por la ansiedad y actuar en armonía con los tiempos naturales.',
  };
}
